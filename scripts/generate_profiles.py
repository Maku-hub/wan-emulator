HEADER = ("# Default profile, generated by scripts/generate_profiles.py (edit there).\n"
          "# A -> B = upload, B -> A = download. Delay and jitter per direction (RTT/2).\n")


def direction(c, rate):
    p = {"delay_ms": c["d"]}
    if c["j"]:
        p.update(jitter_ms=c["j"], distribution="normal", keep_order=True)
    if c["loss"]:
        mode, pct, burst = c["loss"]
        p.update(loss_mode=mode, loss_pct=pct)
        if mode == "burst":
            p["loss_burst_len"] = burst
    if rate:
        p["rate_kbit"] = rate
    if c.get("mtu"):
        p["mtu"] = c["mtu"]
    return p


def main():
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("*.yaml"):
        old.unlink()
    for fname, (name, desc), (name_pl, desc_pl), c in PROFILES:
        doc = {"name": name, "description": desc,
               "translations": {"pl": {"name": name_pl, "description": desc_pl}},
               "a_to_b": direction(c, c["up"]), "b_to_a": direction(c, c["down"])}
        (OUT / f"{fname}.yaml").write_text(HEADER + yaml.safe_dump(doc, allow_unicode=True, sort_keys=False),
                                          encoding="utf-8", newline="\n")
    print(f"{len(PROFILES)} profiles written to {OUT}")


if __name__ == "__main__":
    main()
