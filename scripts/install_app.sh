#!/usr/bin/env bash
# Install or update the web panel on the emulator host.
#   sudo ./scripts/install_app.sh [--update-profiles]
#
#   /opt/wanemu/wanemu        application code (replaced on every install)
#   /etc/wanemu/config.yaml   panel settings, generated from config/wanemu.conf
#   /var/lib/wanemu/profiles  profiles (defaults added only if missing)
#
# --update-profiles overwrites the default profiles with the repository versions
# (profiles created by users are left alone).
set -euo pipefail
# shellcheck source=SCRIPTDIR/common.sh
. "$(dirname "$0")/common.sh"

[ "$(id -u)" = 0 ] || { echo "Run as root (sudo)." >&2; exit 1; }

UPDATE_PROFILES=0
[ "${1:-}" = "--update-profiles" ] && UPDATE_PROFILES=1

install -d /opt/wanemu /etc/wanemu /var/lib/wanemu/profiles

rm -rf /opt/wanemu/wanemu
cp -r "$ROOT/app/wanemu" /opt/wanemu/
find /opt/wanemu -name '__pycache__' -prune -exec rm -rf {} +

cat > /etc/wanemu/config.yaml <<EOF
# /etc/wanemu/config.yaml - generated by scripts/install_app.sh from config/wanemu.conf
iface_a: $PORT_A
iface_b: $PORT_B
default_mtu: 1500
profiles_dir: /var/lib/wanemu/profiles
state_file: /var/lib/wanemu/state.json
EOF

for f in "$ROOT"/profiles/*.yaml; do
    dest="/var/lib/wanemu/profiles/$(basename "$f")"
    if [ "$UPDATE_PROFILES" = 1 ] || [ ! -e "$dest" ]; then install -m 644 "$f" "$dest"; fi
done

sed "s/@PANEL_PORT@/$PANEL_PORT/" "$ROOT/config/systemd/wanemu.service" > /etc/systemd/system/wanemu.service
systemctl daemon-reload
systemctl enable wanemu.service >/dev/null 2>&1
systemctl restart wanemu.service

sleep 1
systemctl --no-pager --lines=0 status wanemu.service || true
addr="${MGMT_ADDRESS%/*}"
[ -n "$addr" ] || addr="$(hostname -I | awk '{print $1}')"
echo "Panel: http://$addr:$PANEL_PORT"
